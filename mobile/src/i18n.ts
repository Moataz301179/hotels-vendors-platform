const dictionaries: Record<Language, Dictionary> = { en, ar };

export function t(lang: Language, key: TranslationKey): string {
  const value = dictionaries[lang][key];
  return typeof value === 'string' ? value : key;
}

export function statusLabel(lang: Language, status: string): string {
  const map = dictionaries[lang].status as Record<string, string>;
  return map[status] ?? status.replaceAll('_', ' ');
}

export function notificationLabel(lang: Language, type: string): string {
  const map = dictionaries[lang].notificationTypes as Record<string, string>;
  return map[type] ?? type.replaceAll('_', ' ');
}
